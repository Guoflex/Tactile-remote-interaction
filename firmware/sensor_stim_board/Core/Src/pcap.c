static volatile uint8_t pcap01_rx[I2C_RX_MAX];
static volatile uint8_t pcap01_read_done = 0;
static volatile uint8_t pcap01_wait_read_bytes = 0;

static void pcap01_send_cmd(uint8_t cmd)
{
    HAL_StatusTypeDef status = HAL_I2C_Master_Transmit(&hi2c2, PCAP01_IIC_ADDR, &cmd, 1, HAL_MAX_DELAY);
    if (status != HAL_OK)
    {
        DBG_PRINTF("PCAP01 Send Cmd Failed: 0x%02X\r\n", cmd);
    }
}

static void pcap01_write_sram(uint16_t addr, uint8_t data)
{
    uint8_t value[3];
    uint16_t cmd_2 = PCAP01_WRITE_SRAM | addr;

    value[0] = (cmd_2 >> 8) & 0xFF;
    value[1] = cmd_2 & 0xFF;
    value[2] = data;

    HAL_StatusTypeDef status = HAL_I2C_Master_Transmit(&hi2c2, PCAP01_IIC_ADDR, value, 3, HAL_MAX_DELAY);
    if (status != HAL_OK)
    {
        DBG_PRINTF("PCAP01 Write SRAM Failed: Addr 0x%02X Data 0x%02X\r\n", addr, data);
    }
}

void pcap01_read_sram_start(uint16_t addr)
{
    uint16_t cmd = PCAP01_READ_SRAM | addr;
    uint8_t pcap01_tx[2];
    pcap01_tx[0] = (cmd >> 8) & 0xFF;
    pcap01_tx[1] = cmd & 0xFF;
    pcap01_read_done = 0;
    pcap01_wait_read_bytes = 1;
    HAL_I2C_Master_Seq_Transmit_IT(&hi2c2, PCAP01_IIC_ADDR, pcap01_tx, 2, I2C_FIRST_FRAME);
}

static uint8_t pcap01_read_sram(uint16_t addr)
{

    pcap01_read_sram_start(addr);

    // DBG_PRINTF("PCAP01 Read SRAM Start: Addr 0x%02X, wait for completion\r\n", addr);

    while (!pcap01_read_done)
    {
        // 喂狗
        HAL_IWDG_Refresh(&hiwdg1);
    }

    return pcap01_rx[0];
}

